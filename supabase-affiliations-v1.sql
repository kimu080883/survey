create or replace function public.apply_employee_department_change(
  p_employee_id text,
  p_department_id text,
  p_effective_date date
) returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_department_name text;
begin
  select name into v_department_name
  from public.departments
  where id = p_department_id and active = true;

  if v_department_name is null then
    raise exception 'INVALID_DEPARTMENT';
  end if;

  if not exists (select 1 from public.employees where id = p_employee_id) then
    raise exception 'INVALID_EMPLOYEE';
  end if;

  update public.employee_department_history
     set valid_to = p_effective_date - 1
   where employee_id = p_employee_id
     and valid_from < p_effective_date
     and (valid_to is null or valid_to >= p_effective_date);

  insert into public.employee_department_history
    (employee_id, department_id, valid_from, valid_to)
  values
    (p_employee_id, p_department_id, p_effective_date, null)
  on conflict (employee_id, valid_from) do update set
    department_id = excluded.department_id,
    valid_to = null;

  update public.employees
     set current_department_id = p_department_id,
         department = v_department_name,
         updated_at = now()
   where id = p_employee_id;
end;
$$;

revoke all on function public.apply_employee_department_change(text, text, date)
  from public, anon, authenticated;
grant execute on function public.apply_employee_department_change(text, text, date)
  to service_role;

create or replace function public.set_driving_report_department()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  select h.department_id, d.name
    into new.department_id, new.department_name
    from public.employee_department_history h
    join public.departments d on d.id = h.department_id
   where h.employee_id = new.employee_id
     and h.valid_from <= new.report_date
     and (h.valid_to is null or h.valid_to >= new.report_date)
   order by h.valid_from desc
   limit 1;

  if new.department_id is null then
    select e.current_department_id, e.department
      into new.department_id, new.department_name
      from public.employees e
     where e.id = new.employee_id;
  end if;

  return new;
end;
$$;

revoke all on function public.set_driving_report_department()
  from public, anon, authenticated;

