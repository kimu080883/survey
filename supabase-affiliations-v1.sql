  id text primary key,
  name text not null unique,
  active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.employee_department_history (
  id bigint generated by default as identity primary key,
  employee_id text not null references public.employees(id),
  department_id text not null references public.departments(id),
  valid_from date not null,
  valid_to date,
  created_at timestamptz not null default now(),
  constraint employee_department_history_dates_check
    check (valid_to is null or valid_to >= valid_from),
  constraint employee_department_history_employee_start_key
    unique (employee_id, valid_from)
);

create unique index if not exists employee_department_history_current_key
  on public.employee_department_history(employee_id)
  where valid_to is null;

